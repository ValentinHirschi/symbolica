pub(super) fn default_options() -> PrintOptions {
    PrintOptions::new()
        .mode(PrintMode::MathML)
        .multiplication_operator('·')
        .num_exp_as_superscript(true)
        .max_terms(Some(100))
}

/// Escape the surrounding prose, inserting only MathML generated by us.
pub(super) fn with_math(format: impl FnOnce(&dyn Fn(&Atom) -> String) -> String) -> String {
    let fragments = std::cell::RefCell::new(Vec::new());
    let text = format(&|atom| {
        let mut fragments = fragments.borrow_mut();
        let marker = format!("\u{e000}{}\u{e001}", fragments.len());
        fragments.push(preview(&atom.as_view().render_mathml_page(
            &default_options(),
            0,
            mathml::DEFAULT_PAGE_SIZE,
        )));
        marker
    });
    let fragments = fragments.into_inner();
    let mut html = String::new();
    let mut rest = text.as_str();
    while let Some((before, after)) = rest.split_once('\u{e000}') {
        html.push_str(&crate::printer::AnsiHtmlFormatter::escape_html(before));
        if let Some((index, tail)) = after.split_once('\u{e001}')
            && let Ok(index) = index.parse::<usize>()
            && let Some(fragment) = fragments.get(index)
        {
            html.push_str(fragment);
            rest = tail;
        } else {
            html.push('\u{e000}');
            rest = after;
        }
    }
    html.push_str(&crate::printer::AnsiHtmlFormatter::escape_html(rest));
    html
}

// The Python expression is frozen. Retain its original owner and borrow the
// storage for the cache's lifetime, without cloning the Atom or its byte buffer.
self_cell!(
    struct CachedExpression {
        owner: Py<PythonExpression>,
        #[covariant]
        dependent: MathMlCursorCache,
    }
);

#[pyclass]
struct PageSource {
    cursors: CachedExpression,
    options: PrintOptions,
}

#[pymethods]
impl PageSource {
    #[pyo3(signature = (path, start, size, layout=0, expansions=None))]
    fn page(
        &self,
        py: Python<'_>,
        path: Vec<usize>,
        start: usize,
        size: usize,
        layout: usize,
        expansions: Option<Vec<(Vec<usize>, usize)>>,
    ) -> PyResult<Py<PyDict>> {
        if !(1..=500).contains(&size) {
            return Err(exceptions::PyValueError::new_err(
                "page_size must be between 1 and 500",
            ));
        }
        if layout >= mathml::LAYOUTS.len() {
            return Err(exceptions::PyValueError::new_err("Unknown layout"));
        }
        let cursors = self.cursors.borrow_dependent();
        let atom = cursors
            .locate(&path)
            .ok_or_else(|| exceptions::PyValueError::new_err("Unknown subexpression"))?;
        let expansions = expansions.unwrap_or_default();
        if expansions
            .iter()
            .any(|(path, count)| path.len() > 64 || !(1..=500).contains(count))
        {
            return Err(exceptions::PyValueError::new_err(
                "Invalid expansion budget",
            ));
        }
        let page = atom.render_mathml_layout_cached(
            &self.options,
            start,
            size,
            layout,
            &expansions,
            cursors,
        );
        let result = PyDict::new(py);
        result.set_item("html", &page.html)?;
        result.set_item("start", page.start)?;
        result.set_item("end", page.end)?;
        result.set_item("total", page.total)?;
        result.set_item("next", (page.end < page.total).then_some(page.end))?;
        let (kind, unit) = match atom {
            AtomView::Fun(_) if page.custom => ("Function", "expressions"),
            AtomView::Add(_) => ("Sum", "terms"),
            AtomView::Mul(_) => ("Product", "factors"),
            AtomView::Fun(_) => ("Function", "arguments"),
            AtomView::Pow(_) => ("Power", "expressions"),
            _ => ("Value", "expressions"),
        };
        result.set_item("kind", kind)?;
        result.set_item("unit", unit)?;
        result.set_item("layout", layout)?;
        let mut markers = Vec::new();
        let mut marker_ids = Vec::new();
        let mut marker_starts = Vec::new();
        for (index, hole) in page.markers.into_iter().enumerate() {
            if hole.path.is_empty() && hole.start == 0 {
                continue;
            }
            let mut target = path.clone();
            target.extend(hole.path);
            markers.push((target, hole.label));
            marker_ids.push(index);
            marker_starts.push(hole.start);
        }
        result.set_item("markers", markers)?;
        result.set_item("marker_ids", marker_ids)?;
        result.set_item("marker_starts", marker_starts)?;
        Ok(result.unbind())
    }
}

pub(super) fn viewer(
    py: Python<'_>,
    expression: Py<PythonExpression>,
    options: PrintOptions,
    size: usize,
) -> PyResult<Py<PyAny>> {
    if !(1..=500).contains(&size) {
        return Err(exceptions::PyValueError::new_err(
            "page_size must be between 1 and 500",
        ));
    }
    mathml_viewer(
        py,
        Py::new(
            py,
            PageSource {
                cursors: CachedExpression::new(expression, |owner| {
                    MathMlCursorCache::new(owner.get().expr.as_view())
                }),
                options,
            },
        )?
        .into_any(),
        size,
        mathml::LAYOUTS.len(),
        true,
    )
}

pub(super) fn is_mathml_viewer(value: &Bound<'_, PyAny>) -> bool {
    value.is_instance_of::<paging::PythonMathMLViewer>()
}

pub(super) fn scrollable_html(html: &str) -> String {
    if let Some(html) = html::wrapping_mathml(html) {
        return format!(
            "<span style=\"display:block;width:100%;max-width:100%;min-width:0;overflow-x:auto\"><span style=\"display:block;padding:.6em .1em;font-size:21px\">{html}</span></span>"
        );
    }
    // Keep the MathML root unconstrained. The inner HTML box includes room for
    // glyph ink outside its line box; only the outer box handles scrolling.
    format!(
        "<span style=\"display:inline-block;max-width:100%;min-width:0;overflow-x:auto;vertical-align:middle\"><span style=\"display:block;width:max-content;padding:.3em .1em;font-size:21px\">{html}</span></span>"
    )
}

/// Native MathML for algebraic containers, independent of notebook packages.
pub(super) fn algebraic_fragment_html(fragment: &str) -> String {
    let html = mathml::document(fragment);
    let html = html::wrapping_mathml(&html).unwrap_or(html);
    // Flex MathML can have ink below its line box. Include that ink inside the
    // HTML scrollport, and give wrapping rows the container's available width.
    format!(
        "<span style=\"display:block;width:100%;max-width:100%;min-width:0;overflow-x:auto\"><span style=\"display:block;padding:.6em .1em;font-size:21px\">{html}</span></span>"
    )
}

pub(super) fn algebraic_html(value: &impl mathml::AlgebraicMathMl) -> String {
    let page = value
        .page(&default_options(), &[], 0, mathml::DEFAULT_PAGE_SIZE)
        .unwrap();
    algebraic_fragment_html(&page.fragment())
}

pub(super) fn preview(page: &MathMlPage) -> String {
    let html = scrollable_html(&page.html);
    if page.is_partial() {
        format!(
            "<div>{}<p>Expression preview · items {}–{} of {}. Omitted subexpressions are marked ⋯. Use .formatted(page_size=25) in a live notebook with symbolica[notebook] to navigate.</p></div>",
            html,
            page.start + 1,
            page.end,
            page.total
        )
    } else {
        html
    }
}

pub(super) fn formatted(
    py: Python<'_>,
    expression: Py<PythonExpression>,
    options: PrintOptions,
    size: usize,
) -> PyResult<PythonFormattedOutput> {
    if !(1..=500).contains(&size) {
        return Err(exceptions::PyValueError::new_err(
            "page_size must be between 1 and 500",
        ));
    }
    let notebook_expression = expression.clone_ref(py);
    let notebook_options = options.clone();
    Ok(PythonFormattedOutput::lazy(move |_, backend| {
        if backend == FormattedOutputBackend::Latex {
            return Ok(None);
        }
        let expression = &expression.get().expr;
        let page = expression.as_view().render_mathml_page(&options, 0, size);
        Ok(Some(match backend {
            FormattedOutputBackend::Html => preview(&page),
            FormattedOutputBackend::Text if page.is_partial() => format!(
                "Symbolica expression preview (items 1–{} of {}; use .formatted(page_size=25) to navigate)",
                page.end, page.total
            ),
            FormattedOutputBackend::Text => expression.format_string(
                &PrintOptions {
                    mode: PrintMode::Symbolica,
                    color_mode: ColorMode::Never,
                    ..options.clone()
                },
                PrintState::new(),
            ),
            FormattedOutputBackend::Latex => unreachable!(),
        }))
    })
    // Static output never constructs the live provider. Small expressions also
    // use the shared viewer when displayed in a notebook, for keyboard zoom.
    .with_notebook(move |py| {
        viewer(py, notebook_expression.clone_ref(py), notebook_options.clone(), size)
    }))
}

fn paging_module(py: Python<'_>) -> PyResult<Bound<'_, PyModule>> {
    let modules = py.import("sys")?.getattr("modules")?;
    let name = "_symbolica_paging";
    let module = if let Ok(module) = modules.get_item(name) {
        module.cast_into::<PyModule>()?
    } else {
        let module = PyModule::new(py, name)?;
        module.add_class::<MathMLMarker>()?;
        module.add_class::<MathMLPage>()?;
        module.add_class::<paging::PythonMathMLViewer>()?;
        // Runtime structural protocol; the full provider signature lives in the stub.
        let typing = py.import("typing")?;
        let base = typing
            .getattr("Protocol")
            .or_else(|_| py.import("builtins")?.getattr("object"))?;
        let attributes = PyDict::new(py);
        attributes.set_item("__module__", name)?;
        attributes.set_item(
            "__doc__",
            "A provider implementing page(path, start, size, layout, expansions).",
        )?;
        let annotations = PyDict::new(py);
        annotations.set_item("page", typing.getattr("Callable")?)?;
        attributes.set_item("__annotations__", annotations)?;
        let protocol = py.import("builtins")?.getattr("type")?.call1((
            "MathMLPageSource",
            (base,),
            attributes,
        ))?;
        module.add("MathMLPageSource", protocol)?;
        modules.set_item(name, &module)?;
        module
    };
    Ok(module)
}

pub(super) fn register(m: &Bound<'_, PyModule>) -> PyResult<()> {
    let module = paging_module(m.py())?;
    for name in [
        "MathMLViewer",
        "MathMLPage",
        "MathMLMarker",
        "MathMLPageSource",
    ] {
        let class = module.getattr(name)?;
        class.setattr("__module__", m.name()?)?;
        m.add(name, class)?;
    }
    Ok(())
}

/// Construct the shared notebook viewer for a community module's page source.
///
/// The source is a Python/PyO3 object implementing the MathMLPageSource protocol.
/// It retains the native expression and renders only bounded requested pages.
/// Use one layout and disable expansion for a minimal adapter. No notebook
/// dependencies are imported until the returned viewer is displayed.
pub fn mathml_viewer(
    py: Python<'_>,
    source: Py<PyAny>,
    page_size: usize,
    layout_count: usize,
    supports_expansion: bool,
) -> PyResult<Py<PyAny>> {
    let kwargs = PyDict::new(py);
    kwargs.set_item("layout_count", layout_count)?;
    kwargs.set_item("supports_expansion", supports_expansion)?;
    paging_module(py)?
        .getattr("MathMLViewer")?
        .call((source, page_size), Some(&kwargs))
        .map(Bound::unbind)
}
